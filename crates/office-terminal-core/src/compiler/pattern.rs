/// One pattern tile's edge: eight logical cells of eight bitmap pixels each,
/// i.e. 8 pt in EMU. ref pattern-bitmaps.ts:82-84 (`createAuxCanvas(64, 64)`).
pub const PATTERN_BITMAP_EDGE: u32 = 64;

/// The eight-by-eight cell rows for `preset`, or `None` for an unknown name
/// (the reference then falls back to the foreground colour).
pub fn pattern_rows(preset: &str) -> Option<&'static str> {
    PATTERN_BITMAPS
        .iter()
        .find(|(name, _)| *name == preset)
        .map(|(_, rows)| *rows)
}

/// Half-way blend of the two pattern colours, used for the `+` cells.
fn midpoint(fg: [u8; 4], bg: [u8; 4]) -> [u8; 4] {
    let mix = |a: u8, b: u8| (u16::from(a) + u16::from(b)).div_ceil(2) as u8;
    [
        mix(fg[0], bg[0]),
        mix(fg[1], bg[1]),
        mix(fg[2], bg[2]),
        mix(fg[3], bg[3]),
    ]
}

/// Render the measured cell at PowerPoint PDF's native 8×8 sample resolution:
/// a 64×64 straight-RGBA tile of uniform 8×8 blocks.
/// ref pattern-bitmaps.ts:80-108.
pub fn build_pattern_bitmap(preset: &str, fg: [u8; 4], bg: [u8; 4]) -> Option<Vec<u8>> {
    let rows = pattern_rows(preset)?;
    let rows: Vec<&str> = rows.split('/').collect();
    let plus = midpoint(fg, bg);
    let edge = PATTERN_BITMAP_EDGE as usize;
    let mut pixels = vec![0u8; edge * edge * 4];
    for y in 0..edge {
        let row = rows.get(y / 8)?;
        for x in 0..edge {
            let cell = row.as_bytes().get(x / 8).copied()?;
            let rgba = match cell {
                b'#' => fg,
                b'+' => plus,
                _ => bg,
            };
            let i = (y * edge + x) * 4;
            pixels[i..i + 4].copy_from_slice(&rgba);
        }
    }
    Some(pixels)
}
