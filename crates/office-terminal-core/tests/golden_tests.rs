//! Golden-image E2E tests for the deck-to-pixels pipeline.
//!
//! Each fixture deck is loaded, compiled and rasterized through the same
//! production seam as `office-terminal-cli export --format png`, then compared
//! against committed reference PNGs under `tests/golden/png/<deck>/`.
//!
//! Fixtures are generated in-repo. Deck-dependent tests print a SKIP note and
//! return when a generated fixture is absent, so a partial corpus never blocks
//! the build.
//!
//! Regenerate the fixture first:
//!
//! ```sh
//! cd crates/office-terminal-core/tests/golden
//! npm ci
//! NODE_PATH="$PWD/node_modules" node gen_pptxgenjs.js fixtures/pptxgenjs_sample.pptx
//! python3 normalize_pptx.py fixtures/pptxgenjs_sample.pptx
//! ```
//!
//! Then refresh references after an intentional rendering change:
//!
//! ```sh
//! UPDATE_GOLDENS=1 cargo test -p office-terminal-core --test golden_tests
//! ```
//!
//! The font stack matters: goldens are generated with DejaVu Sans installed
//! (see `tests/golden/README.md`). Different fonts change glyph rasterization
//! and require regenerating the text-heavy decks.

mod golden_support;

use crossbeam_channel::unbounded;
use golden_support::{compare_or_update, render_deck, sample_fractional, DeckConfig, Thresholds};
use office_terminal_core::{
    DefaultPresentationLoader, DefaultSlideCompiler, PresentationLoader, RgbaSlide, SlideCompiler, SlideRasterizer,
    Source, TinySkiaRasterizer,
};

/// One row per committed fixture deck.
///
/// `width_px` is fixed for reproducibility; the height is derived from the
/// slide aspect ratio. Tune the thresholds here when a deck legitimately
/// needs more slack (for example a deck dominated by text on CI images with a
/// different font stack). The default policy is deliberately strict: a real
/// renderer regression moves millions of pixels, not a handful of AA edges.
const DECKS: &[DeckConfig] = &[
    DeckConfig {
        name: "pptxgenjs_sample",
        width_px: 800,
        thresholds: Thresholds::DEFAULT,
    },
    // WordArt `textDeflate` warp over three paragraphs: guards the paired-edge
    // envelope map (glyph `u` → `P(u, v)`), which used to emit black shards.
    // The deck is 100 % text, so a host with a different font stack moves every
    // glyph edge; the loose policy is the same one text-dominated decks use.
    // Generated by `tests/warp_parity_tests.rs`.
    DeckConfig {
        name: "warp_textdeflate",
        width_px: 800,
        thresholds: Thresholds::LOOSE,
    },
];

fn deck(name: &str) -> &'static DeckConfig {
    DECKS
        .iter()
        .find(|config| config.name == name)
        .unwrap_or_else(|| panic!("no golden config for deck {name}"))
}

fn run_deck(config: &'static DeckConfig) {
    if !golden_support::fixture_available(config.name) {
        eprintln!(
            "SKIP {}: generated fixture is not present; see tests/golden/README.md",
            config.name
        );
        return;
    }
    let rendered = render_deck(config);
    assert!(
        !rendered.slides.is_empty(),
        "{}: fixture contains no slides",
        config.name
    );
    for index in 0..rendered.slides.len() {
        let label = format!("{} slide {}", config.name, index + 1);
        compare_or_update(&rendered, index, &label);
    }
}

#[test]
fn golden_pptxgenjs_sample() {
    run_deck(deck("pptxgenjs_sample"));
}

#[test]
fn golden_warp_textdeflate() {
    run_deck(deck("warp_textdeflate"));
}

